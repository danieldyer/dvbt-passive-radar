"""Minimax Bernoulli log-loss quantiser, exhaustive on a half-LLR grid.

Fifteen symmetric levels, including zero and +/-7. The bound concerns added
quantisation loss for calibrated, already bounded LLRs, not CSI/model error.
"""

import argparse
import itertools
import json
import math
from pathlib import Path

p = argparse.ArgumentParser()
p.add_argument("output", type=Path)
p.add_argument("--header", type=Path)
p.add_argument("--glsl", type=Path)
args = p.parse_args()


def probability(llr):
    return 1 / (1 + math.exp(-llr))


def divergence(p, q):
    return p * math.log(p / q) + (1 - p) * math.log((1 - p) / (1 - q))


edges = {}
for i in range(14):
    for j in range(i + 1, 15):
        a, b = i / 2, j / 2
        # Equal posterior cross-entropy gives the optimal decision boundary
        # for fixed reconstruction levels; p is the posterior of bit zero.
        posterior = (math.log1p(math.exp(b)) - math.log1p(math.exp(a))) / (b - a)
        threshold = math.log(posterior / (1 - posterior))
        left = divergence(posterior, probability(a))
        right = divergence(posterior, probability(b))
        assert abs(left - right) < 1e-12
        edges[i, j] = left, threshold

best = (math.inf, math.inf, ())
for interior in itertools.combinations(range(1, 14), 6):
    levels = (0, *interior, 14)
    costs = [edges[a, b][0] for a, b in itertools.pairwise(levels)]
    best = min(best, (max(costs), sum(costs), levels))
levels = best[2]
thresholds = [edges[a, b][1] for a, b in itertools.pairwise(levels)]
uniform_loss = max(
    divergence(probability(i + 0.5), probability(j)) for i in range(7) for j in (i, i + 1)
)
result = {
    "levels_half_units": levels,
    "positive_thresholds": thresholds,
    "worst_loss_bits": best[0] / math.log(2),
    "uniform_worst_loss_bits": uniform_loss / math.log(2),
    "searched_codebooks": math.comb(13, 6),
    "design": "minimax posterior log-loss, fixed clipped LLR domain",
}
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text(json.dumps(result, indent=2) + "\n")
if args.header:
    args.header.write_text(
        "#pragma once\n// Generated by scripts/design_feedback_quantizer.py; no capture-specific fit.\n"
        "#include <array>\nnamespace radar::fec {\n"
        "// Nonnegative reconstruction values in half-LLR units; code = 7 +/- rank.\n"
        "inline constexpr std::array<int,8> minimax_llr_levels{"
        + ",".join(map(str, levels))
        + "};\n"
        "inline constexpr std::array<float,7> minimax_llr_thresholds{"
        + ",".join(f"{x:.9g}F" for x in thresholds)
        + "};\n}\n"
    )
if args.glsl:
    args.glsl.write_text(
        "// Generated by scripts/design_feedback_quantizer.py; same levels as soft_quantizer.hpp.\n"
        "uint minimax_likelihood(float x){\n    if(isnan(x))return 7;\n    float a=abs(x);uint rank=0;\n"
        + "".join(f"    rank+=uint(a>={x:.9g});\n" for x in thresholds)
        + "    return x<0 ? 7-rank : 7+rank;\n}\n"
    )
print(json.dumps(result, indent=2))
