"""Conservative decoder-only frequency smoothing; full GI delay support.

The centred dense pilot grid is spaced three carriers apart. Its largest
in-guard delay is GI/2, hence a pass edge of 3/(2*guard_denominator) cycles/grid
sample. No measured channel or payload tunes the coefficients.
"""

import argparse
import json
from pathlib import Path

import numpy as np
from scipy.signal import firwin, freqz

p = argparse.ArgumentParser()
p.add_argument("output", type=Path)
p.add_argument("--header", type=Path)
args = p.parse_args()
args.output.mkdir(parents=True, exist_ok=True)
result = []
filters = []
for guard in range(4):
    denominator = 32 >> guard
    edge = 3 / (2 * denominator)
    taps = firwin(49, edge + 0.055, window=("kaiser", 7.9), fs=1)
    frequency, response = freqz(taps, worN=65536, fs=1)
    zero_phase = response * np.exp(2j * np.pi * frequency * 24)
    ripple = float(np.max(np.abs(zero_phase[frequency <= edge] - 1)))
    rejection = float(-20 * np.log10(np.max(np.abs(response[frequency >= edge + 0.11]))))
    if ripple > 0.001 or rejection < 60:
        raise RuntimeError("Prototype failed guard-support gate")
    np.savetxt(args.output / f"guard-{denominator}.txt", taps, fmt="%.17g")
    filters.append(taps)
    result.append(
        {
            "guard_denominator": denominator,
            "taps": len(taps),
            "pass_edge": edge,
            "pass_complex_error": ripple,
            "stop_rejection_db": rejection,
            "white_noise_gain": float(np.sum(taps * taps)),
        }
    )
(args.output / "design.json").write_text(json.dumps(result, indent=2) + "\n")
if args.header:
    text = """#pragma once
// Generated by scripts/design_pilot_filter.py. Dense pilot spacing
// is three carriers. Passband covers the full centred guard interval; a fixed
// 0.11-cycle transition suppresses estimation noise without fitting RF data.
#include <array>
namespace radar {
inline constexpr std::array<std::array<float,49>,4> pilot_frequency_filters{{
"""
    for taps in filters:
        text += "    {{\n"
        for i in range(0, len(taps), 7):
            text += "        " + ",".join(f"{v:.9e}F" for v in taps[i : i + 7]) + ",\n"
        text += "    }},\n"
    args.header.write_text(text + "}};\n}\n")
print(json.dumps(result, indent=2))
