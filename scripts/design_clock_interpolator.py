"""Offline band-limited fractional-delay design; no build/runtime dependency.

The 16 MS/s intermediate covers the channel's 3.671875 MHz rejection edge.
Real least-squares taps approximate exp(i*w*(7+mu)) on that band. A ninth
order polynomial represents each tap over -0.5 <= mu-0.5 <= 0.5. Dense independent
phase/frequency checks include float32 tap rounding and phase-table interpolation.
Run with the existing build/filter-venv/bin/python.
"""

from pathlib import Path

import numpy as np

TAPS, ORDER, BAND = 16, 9, 3671875 / 16e6
f = np.linspace(0, BAND, 4096)
basis = np.exp(2j * np.pi * f[:, None] * np.arange(TAPS))
mu = np.linspace(0, 1, 65)
target = np.exp(2j * np.pi * f[:, None] * (7 + mu))
taps = np.linalg.lstsq(
    np.concatenate([basis.real, basis.imag]), np.concatenate([target.real, target.imag]), rcond=None
)[0]
polynomial = np.polynomial.polynomial.polyfit(mu - 0.5, taps.T, ORDER).T
phases = np.arange(2049) / 2048
h = np.array([np.polynomial.polynomial.polyval(phases - 0.5, row) for row in polynomial]).T.astype(
    np.float32
)
maximum = 0.0
for phase in np.linspace(0, 1, 257):
    at = phase * 2048
    p = min(2047, int(at))
    alpha = at - p
    weights = (1 - alpha) * h[p].astype(float) + alpha * h[p + 1].astype(float)
    response = np.sum(basis * weights, axis=1)
    maximum = max(maximum, float(np.max(abs(response - np.exp(2j * np.pi * f * (7 + phase))))))
assert maximum < 1e-6, maximum
print("16-tap interpolator maximum complex error:", maximum)
lines = [
    "// Generated by scripts/design_clock_interpolator.py.",
    "// 16 MS/s; passband through 3.671875 MHz; measured complex error < 1e-6.",
    "#pragma once",
    "#include <array>",
    "namespace radar::filters {",
    "inline constexpr std::array<std::array<double,10>,16> clock_polynomial = {{",
]
lines += ["    {" + ", ".join(f"{v:.17e}" for v in row) + "}," for row in polynomial]
lines += ["}};", "}"]
(Path(__file__).resolve().parents[1] / "src/clock_filter.hpp").write_text("\n".join(lines) + "\n")

# The common oscillator's slow drift leaves at most 0.002 intermediate samples
# after the spectral phase ramp. Fit its odd first derivative on the occupied
# band; the centred second difference supplies the quadratic term.
w = np.linspace(0, 2 * np.pi * 3328125 / 16e6, 4096)
derivative = np.linalg.lstsq(2 * np.sin(w[:, None] * np.arange(1, 4)), w, rcond=None)[0]
print("Small residual differentiator weights:", ", ".join(f"{v:.17g}" for v in derivative))
